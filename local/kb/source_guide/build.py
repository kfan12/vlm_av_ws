"""build_guide.py - merge the extracted functions with the hand-written explanations and write
the source guide page (local/kb/source_guide.html and a publishable copy)."""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
import descriptions as K

src = json.load(open(os.path.join(HERE, 'extracted.json')))
EM = chr(0x2014)


def clean(t, n=420):
    t = (t or '').replace(EM, ' - ').replace('–', '-')
    t = re.sub(r'\s+', ' ', t).strip()
    return t if len(t) <= n else t[:n].rsplit(' ', 1)[0] + ' ...'


files = {}
users = {}
for node, r in src['nodes'].items():
    for f in r['files']:
        users.setdefault(f, []).append(node)

missing_desc = []
for f, v in src['files'].items():
    base = os.path.basename(f)
    items = []
    for it in v['items']:
        key = f'{base}::{it["name"]}'
        if key in K.FN:
            doc, how = K.FN[key], 'explained'
        elif it['doc']:
            doc, how = clean(it['doc']), 'comment'
        else:
            doc, how = '', 'none'
            if it['kind'] == 'fn':
                missing_desc.append(key)
        items.append({'k': it['kind'], 'n': it['name'], 'l': it['line'], 'e': it.get('end', it['line']),
                      's': clean(it['sig'], 300), 'd': doc, 'h': how})
    role = K.FILE_ROLE.get(base) or clean(v['header'], 520)
    files[f] = {'loc': v['loc'], 'role': role, 'users': users.get(f, []), 'items': items}

nodes = {}
unresolved = []
no_meta = []
grouped = {n for _, names in K.GROUPS for n in names}
for node, r in src['nodes'].items():
    meta = K.NODES.get(node)
    if meta is None:
        no_meta.append(node)
        meta = {'role': 'No description yet (add it to local/kb/source_guide/descriptions.py NODES).',
                'setups': '-', 'trigger': '-', 'flow': []}
    if node not in grouped:
        no_meta.append(f'{node} (not in GROUPS)')
    flow = []
    for fn, text in meta['flow']:
        hit = None
        for f in r['files']:
            for it in files[f]['items']:
                if it['n'] == fn or it['n'].endswith('::' + fn) or it['n'].endswith('.' + fn):
                    hit = (f, it['l'], it['n'])
                    break
            if hit:
                break
        if not hit:
            unresolved.append(f'{node}: {fn}')
        flow.append({'fn': fn, 't': text, 'f': hit[0] if hit else None, 'l': hit[1] if hit else None})
    nodes[node] = {'pkg': r['package'], 'files': r['files'], 'role': meta['role'], 'setups': meta['setups'],
                   'trigger': meta['trigger'], 'flow': flow}

groups = [(g, [n for n in names if n in nodes]) for g, names in K.GROUPS]
extra = sorted(n for n in nodes if n not in grouped)
if extra:
    groups.append(('Not yet grouped', extra))
data = {'groups': groups, 'nodes': nodes, 'files': files, 'built': __import__('datetime').date.today().isoformat()}
n_fn = sum(1 for v in files.values() for i in v['items'] if i['k'] == 'fn')
n_doc = sum(1 for v in files.values() for i in v['items'] if i['k'] == 'fn' and i['d'])
print(f'nodes {len(nodes)}  files {len(files)}  functions {n_fn}  described {n_doc}')
print('unresolved flow refs:', unresolved or 'none')
print('functions without description:', missing_desc or 'none')

tpl = open(os.path.join(HERE, 'template.html'), encoding='utf-8').read()
page = tpl.replace('/*__DATA__*/null', json.dumps(data, ensure_ascii=False).replace('</', '<\\/'))
assert EM not in page, 'em dash in page'

if len(sys.argv) > 1:  # optional: also write the bare page for publishing as an artifact
    open(sys.argv[1], 'w', encoding='utf-8', newline='\n').write(page)
head_end = page.index('</style>') + len('</style>')
note = ('<!-- Per node: its source files, every function with its line range, and what it does.\n'
        '     Generated by local/kb/source_guide/build.sh from the code (function list) plus hand-written explanations read from the code.\n'
        '     Line numbers drift as the code changes: regenerate rather than hand-edit. -->\n')
full = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        + note + page[:head_end] + '\n<style>body{margin:0}</style>\n</head>\n<body>' + page[head_end:] + '\n</body>\n</html>\n')
open(os.path.join(WS, 'local', 'kb', 'source_guide.html'), 'w', encoding='utf-8', newline='\n').write(full)
print('wrote local/kb/source_guide.html', len(full), 'bytes')
problems = ([f'node without a write-up: {n}' for n in no_meta] + [f'cycle step no longer resolves: {u}' for u in unresolved]
            + [f'function without a description: {m}' for m in missing_desc])
if problems:
    print(f'source guide: {len(problems)} problem(s)')
    print('\n'.join('  ' + p for p in problems))
    sys.exit(1)
